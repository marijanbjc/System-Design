"""Regex-детекторы безопасности: prompt injection и токсичность.

Живут в одной стадии с нормализацией, поэтому латентности горячему пути не добавляют.
Моделей здесь нет намеренно: на этом рубеже нужен детерминизм и предсказуемая скорость,
а не точность — уточнять вердикт будет человек.
"""

import re

# Явные императивы и разметка-ловушки. Ловим только очевидный слой: перефразировки,
# многоходовки и другие языки сюда не попадают, и это честно названо в документации.
_INJECTION_PATTERNS = [
    r"игнорируй\w*\s+(все\s+)?(предыдущ\w+|прежн\w+|выше)",
    r"забудь\w*\s+(все\s+)?(предыдущ\w+|инструкц\w+|указан\w+)",
    r"ignore\s+(all\s+)?(previous|prior|above)\s+instructions?",
    r"disregard\s+(all\s+)?(previous|prior)\s+",
    r"ты\s+(теперь|отныне)\s+\w+",
    r"you\s+are\s+now\s+",
    r"act\s+as\s+(a|an)\s+",
    r"(system|assistant|user)\s*:\s*",
    r"<\|.*?\|>",
    r"new\s+system\s+prompt",
    r"(закрой|close)\s+тикет\s+автоматич",
]

# Токсичность, угрозы и маркеры тем, которые нельзя закрывать автоматически.
_UNSAFE_PATTERNS = [
    r"\b(идиот\w*|дебил\w*|тварь|ублюд\w*|сволоч\w*|придур\w*)\b",
    r"\b(убью|прикончу|найду\s+тебя|сожгу\s+ваш|разнесу)\b",
    r"\b(подам\s+в\s+суд|подавать\s+в\s+суд|прокуратур\w*|роспотребнадзор)\b",
    r"\b(взлом\w*\s+аккаунт|украли\s+деньги|мошенник\w*)\b",
    r"\b(чарджбэк|chargeback)\b",
]

_INJECTION_RE = re.compile("|".join(_INJECTION_PATTERNS), re.IGNORECASE)
_UNSAFE_RE = re.compile("|".join(_UNSAFE_PATTERNS), re.IGNORECASE)


def detect_injection(text: str) -> bool:
    """Первый дешёвый слой защиты от инъекций.

    Срабатывание уводит тикет к оператору, но никогда не блокирует пользователя:
    «проигнорируйте моё предыдущее письмо» — реальный кейс поддержки, и ложный
    позитив не должен оборачиваться отказом живому человеку. Цена ошибки — один
    оператор, а не потерянное обращение.
    """
    return bool(_INJECTION_RE.search(text))


def detect_unsafe(text: str) -> bool:
    """Грубый, но терминальный предфильтр: срабатывание = сразу к человеку.

    Уточнять этот вердикт флагами модели нечем — на этой ветке LLM не вызывается вовсе.
    """
    return bool(_UNSAFE_RE.search(text))
