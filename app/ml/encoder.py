r"""Локальный энкодер. В PoC это мок на хешировании — см. ml.md §3.

## Как он устроен

Это hashing trick: вместо словаря, который пришлось бы обучать и хранить, каждый токен
детерминированно отображается в номер измерения вектора фиксированной длины.

    токен ──blake2b──> 64-битное число ──% dim──> номер измерения ──> +вес

Для одного текста мы:

1. Режем его на слова регуляркой `\w+` и приводим к нижнему регистру.
2. Каждому слову добавляем вес 1.0 в его измерение.
3. Каждое слово дополнительно режем на символьные триграммы с якорями `^слово$` и
   каждой триграмме добавляем вес поменьше (`encoder_trigram_weight`).
4. Нормализуем вектор по L2 — тогда скалярное произведение двух векторов равно ровно
   косинусной близости, которую и считает Redis с `distance_metric: cosine`.

## Зачем триграммы

Без них «возврат» и «возврата» — два независимых измерения, и русская морфология
рушит любое совпадение. Триграммы `^во`, `воз`, `озв`, `звр`… у этих слов почти
одинаковые, поэтому векторы остаются близкими. Вес триграммы ниже веса слова, чтобы
точное совпадение слова всё же весило больше, чем похожее написание.

## Чего он принципиально не умеет

Это лексическая модель, а не семантическая. «Как оформить возврат» и «хочу отправить
товар обратно» для неё далеки, потому что не пересекаются по словам. Синонимы,
перефразировки и смысл вне лексики ей недоступны — ровно ради этого в целевой
архитектуре здесь стоит контрастивно дообученный sentence-энкодер (ml.md §3).

## Почему в PoC всё-таки мок

Он детерминирован (одинаковый вход — одинаковый вектор всегда), не требует скачивания
весов и работает офлайн, поэтому демо воспроизводимо и запускается за секунды. Замена
на настоящую модель не трогает остальной конвейер: наружу этот модуль отдаёт только
`embed(text) -> np.ndarray` фиксированной размерности.
"""

import hashlib
import re

import numpy as np

from app.config import get_settings

_TOKEN_RE = re.compile(r"\w+", re.UNICODE)
_TRIGRAM_SIZE = 3
_WORD_WEIGHT = 1.0  # база, относительно которой в конфиге задан вес триграммы


def _bucket(token: str, dim: int) -> int:
    """Устойчивый номер измерения для токена.

    blake2b взят как быстрый и стабильный между запусками: встроенный `hash()` в
    Python рандомизирован по процессам, и индекс, собранный вчера, не совпал бы с
    запросом сегодня.
    """
    digest = hashlib.blake2b(token.encode("utf-8"), digest_size=8).digest()
    return int.from_bytes(digest, "big") % dim


def embed(text: str) -> np.ndarray:
    """Закодировать текст в L2-нормализованный вектор float32."""
    settings = get_settings()
    dim = settings.embed_dim
    vector = np.zeros(dim, dtype=np.float32)

    for token in _TOKEN_RE.findall(text.lower()):
        vector[_bucket(token, dim)] += _WORD_WEIGHT
        # Якоря ^ и $ отличают начало и конец слова от середины: так «возврат» и
        # «переворот» не сближаются из-за общей внутренней триграммы «вор».
        padded = f"^{token}$"
        for i in range(len(padded) - _TRIGRAM_SIZE + 1):
            trigram = padded[i : i + _TRIGRAM_SIZE]
            vector[_bucket(trigram, dim)] += settings.encoder_trigram_weight

    # Пустой текст даёт нулевой вектор: делить на ноль нельзя, а близость к нему
    # всё равно окажется нулевой и порог его не пропустит.
    norm = float(np.linalg.norm(vector))
    if norm == 0.0:
        return vector
    return vector / norm
