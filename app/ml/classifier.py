"""Мок-классификатор темы и риска: правила по ключевым словам.

В PoC обучать модель избыточно — нужно показать работоспособность маршрутизации, а не
качество классификации. В целевой архитектуре здесь две головы поверх контрастивно
дообученного энкодера (docs/ml.md §3–4); контракт этого модуля при замене не меняется.

## Два свойства правил, которые важны для маршрутизации

**Порядок значим.** Рисковые темы стоят первыми, поэтому «списали деньги за заказ»
уйдёт в `payment_dispute` (высокий риск, только оператор), а не в `payment`. Правило
«первое совпадение выигрывает» ошибается в сторону осторожности, и это осознанно.

**Неопознанное обращение — не ошибка, а сигнал.** Тема `general` приходит с
уверенностью ниже `conf_cls_min`, поэтому роутер перестаёт доверять и теме, и политике
по ней, и уводит обращение к человеку. Молча угадывать тему опаснее, чем признать, что
мы её не знаем.

Ключевые слова — подстроки, а не целые слова: «доставк» ловит «доставка», «доставки»,
«доставкой». Это грубо, но для правил на русском работает лучше точного совпадения.
"""

from dataclasses import dataclass

from app.config import get_settings
from app.models import Risk


@dataclass(frozen=True)
class Prediction:
    """Результат классификации: тема, риск и уверенность."""

    topic: str
    risk: Risk
    conf_cls: float


# тема → (ключевые слова, риск). Порядок = приоритет.
_RULES: list[tuple[str, tuple[str, ...], Risk]] = [
    # --- рисковые темы: закрываются только оператором ---
    (
        "payment_dispute",
        (
            "списали", "списание", "списаны", "двойн", "дважды",
            "верните деньги", "верните средства", "не вернули деньги",
            "чарджбэк", "chargeback", "в суд", "претензи", "компенсаци",
        ),
        Risk.HIGH,
    ),
    (
        "account_security",
        (
            "взлом", "мошен", "украли", "несанкционирован", "утечк",
            "чужой заказ", "не я оформлял", "зашли в мой", "фишинг",
        ),
        Risk.HIGH,
    ),
    # --- обычные темы ---
    (
        "returns",
        (
            "возврат", "вернуть", "возврату", "refund", "обмен", "обменять",
            "брак", "бракован", "не подошёл", "не подошел", "гаранти",
        ),
        Risk.LOW,
    ),
    (
        "delivery",
        (
            "доставк", "доставит", "курьер", "где заказ", "где мой", "когда приедет",
            "трек", "посылк", "пункт выдачи", "самовывоз", "не привезли", "опозда",
        ),
        Risk.LOW,
    ),
    (
        "payment",
        (
            "оплат", "платеж", "платёж", "картой", "карты", "чек", "сбп",
            "не проходит", "способ оплаты", "рассрочк",
        ),
        Risk.LOW,
    ),
    (
        "account",
        (
            "аккаунт", "пароль", "личный кабинет", "код подтверждения", "профил",
            "не могу войти", "регистрац", "email", "почту", "удалить учет",
        ),
        Risk.LOW,
    ),
    (
        "loyalty",
        (
            "бонус", "промокод", "балл", "лояльност", "скидк", "купон",
            "сертификат", "акци", "кэшбэк",
        ),
        Risk.LOW,
    ),
    (
        "catalog",
        (
            "наличи", "есть ли в", "когда появится", "размер", "характеристик",
            "состав", "срок годности", "производител",
        ),
        Risk.LOW,
    ),
]


class Classifier:
    """Определяет тему и риск обращения по ключевым словам."""

    def predict(self, text: str) -> Prediction:
        """Вернуть тему, риск и уверенность для нормализованного текста обращения."""
        settings = get_settings()
        lowered = text.lower()
        for topic, keywords, risk in _RULES:
            if any(keyword in lowered for keyword in keywords):
                return Prediction(
                    topic=topic, risk=risk, conf_cls=settings.classifier_matched_confidence
                )
        return Prediction(
            topic="general", risk=Risk.LOW, conf_cls=settings.classifier_fallback_confidence
        )
