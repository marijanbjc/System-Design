# Компилируем один раз на импорте: горячий путь не должен собирать регулярки на каждый тикет.
_COMPILED: list[tuple[str, re.Pattern[str], Risk]] = [
    (topic, re.compile("|".join(rf"\b{re.escape(kw)}" for kw in keywords), re.IGNORECASE), risk)
    for topic, keywords, risk in _RULES
]


class Classifier:
    """Определяет тему и риск обращения по ключевым словам."""

    def predict(self, text: str) -> Prediction:
        """Вернуть тему, риск и уверенность для нормализованного текста обращения."""
        settings = get_settings()
        for topic, pattern, risk in _COMPILED:
            if pattern.search(text):
                return Prediction(
                    topic=topic, risk=risk, conf_cls=settings.classifier_matched_confidence
                )
        return Prediction(
            topic="general", risk=Risk.LOW, conf_cls=settings.classifier_fallback_confidence
        )
